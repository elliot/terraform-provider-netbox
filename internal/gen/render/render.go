// Package render writes Go sources, tests and examples from the resource model.
package render

import (
	"fmt"
	"go/format"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"golang.org/x/tools/imports"

	"github.com/elliot/terraform-provider-netbox/internal/gen/model"
)

// Options controls output locations.
type Options struct {
	OutDir      string
	ExamplesDir string
	DocsDir     string
	// TemplatesDir receives tfplugindocs templates (subcategory per app).
	TemplatesDir string
	// Partial means only a subset is rendered; stale files are not removed.
	Partial bool
}

// All renders every resource.
func All(resources []*model.Resource, netboxVersion string, opts Options) error {
	version := strings.Fields(netboxVersion)[0]
	apps := map[string][]*model.Resource{}
	for _, r := range resources {
		if r.Skip {
			continue
		}
		apps[r.App] = append(apps[r.App], r)
	}
	if !opts.Partial {
		// Remove previously generated files so deletions propagate. The walk is
		// scoped to an os.Root so symlinks cannot escape OutDir.
		if root, err := os.OpenRoot(opts.OutDir); err == nil {
			_ = fs.WalkDir(root.FS(), ".", func(path string, d fs.DirEntry, err error) error {
				if err == nil && !d.IsDir() && strings.HasSuffix(path, ".go") {
					if data, rerr := root.ReadFile(path); rerr == nil && strings.HasPrefix(string(data), "// Code generated by internal/gen") {
						return root.Remove(path)
					}
				}
				return nil
			})
			_ = root.Close()
		}
	}
	computeSweeperDeps(resources)
	var appNames []string
	for app := range apps {
		appNames = append(appNames, app)
	}
	sort.Strings(appNames)
	for _, app := range appNames {
		dir := filepath.Join(opts.OutDir, pkgName(app))
		if err := os.MkdirAll(dir, 0o750); err != nil {
			return err
		}
		for _, r := range apps[app] {
			if err := renderResource(r, version, dir, opts); err != nil {
				return fmt.Errorf("%s: %w", r.TFType(), err)
			}
		}
	}
	// The registration package lists every app directory present on disk so
	// that partial runs keep previously generated packages registered.
	var onDisk []string
	entries, _ := os.ReadDir(opts.OutDir)
	for _, e := range entries {
		if e.IsDir() && e.Name() != "all" {
			if matches, _ := filepath.Glob(filepath.Join(opts.OutDir, e.Name(), "*.go")); len(matches) > 0 {
				onDisk = append(onDisk, e.Name())
			}
		}
	}
	if err := writeAllPackage(onDisk, version, opts.OutDir); err != nil {
		return err
	}
	if !opts.Partial {
		if err := writeObjectTypes(resources, version, opts.OutDir); err != nil {
			return err
		}
	}
	for _, r := range resources {
		if r.Skip {
			continue
		}
		if err := writeDocTemplates(r, opts.TemplatesDir); err != nil {
			return err
		}
	}
	if !opts.Partial {
		if err := writeResourcesDoc(resources, opts.DocsDir); err != nil {
			return err
		}
	}
	return nil
}

func renderResource(r *model.Resource, version, dir string, opts Options) error {
	if !r.DataSourceOnly {
		src, err := resourceFile(r, version)
		if err != nil {
			return err
		}
		if err := writeGo(filepath.Join(dir, r.Name+"_resource.go"), src); err != nil {
			return err
		}
		if test := testFile(r, version); test != "" {
			if err := writeGo(filepath.Join(dir, r.Name+"_resource_test.go"), test); err != nil {
				return err
			}
		}
		if err := writeExamples(r, opts.ExamplesDir); err != nil {
			return err
		}
	}
	if err := writeGo(filepath.Join(dir, r.Name+"_data_source.go"), dataSourceFile(r, version)); err != nil {
		return err
	}
	return writeDataSourceExamples(r, opts.ExamplesDir)
}

// writeGo formats (goimports) and writes a Go source file.
func writeGo(path, src string) error {
	out, err := imports.Process(path, []byte(src), &imports.Options{Comments: true, TabIndent: true, TabWidth: 8, FormatOnly: false})
	if err != nil {
		// Write the raw source to help debugging, then fail.
		_ = os.WriteFile(path+".broken", []byte(src), 0o600)
		return fmt.Errorf("format %s: %w (raw source written to %s.broken)", path, err, path)
	}
	return os.WriteFile(path, out, 0o600)
}

func writeAllPackage(apps []string, version, outDir string) error {
	dir := filepath.Join(outDir, "all")
	if err := os.MkdirAll(dir, 0o750); err != nil {
		return err
	}
	var b strings.Builder
	fmt.Fprintf(&b, generatedHeader, version)
	b.WriteString("// Package all registers every generated resource and data source with the provider.\npackage all\n\nimport (\n")
	for _, app := range apps {
		fmt.Fprintf(&b, "\t_ \"github.com/elliot/terraform-provider-netbox/internal/provider/gen/%s\"\n", app)
	}
	b.WriteString(")\n")
	return os.WriteFile(filepath.Join(dir, "all.go"), []byte(b.String()), 0o600)
}

func writeResourcesDoc(resources []*model.Resource, docsDir string) error {
	if err := os.MkdirAll(docsDir, 0o750); err != nil {
		return err
	}
	var b strings.Builder
	b.WriteString("# Generated resources and data sources\n\nThis table is generated by `go run ./internal/gen`; do not edit.\n\n")
	b.WriteString("| App | API path | Resource | Data source | List data source | Notes |\n|---|---|---|---|---|---|\n")
	for _, r := range resources {
		res, note := "`"+r.TFType()+"`", ""
		switch {
		case r.Skip:
			res, note = "", "skipped: "+r.SkipReason
		case r.DataSourceOnly:
			res, note = "", "read-only endpoint"
		}
		ds := ""
		if !r.Skip {
			ds = "`data." + r.TFType() + "`"
		}
		lds := ""
		if !r.Skip {
			lds = "`data." + r.TFPluralType() + "`"
		}
		fmt.Fprintf(&b, "| %s | `%s` | %s | %s | %s | %s |\n", r.App, r.Path, res, ds, lds, note)
	}
	return os.WriteFile(filepath.Join(docsDir, "RESOURCES.md"), []byte(b.String()), 0o600)
}

var appTitles = map[string]string{
	"circuits": "Circuits", "core": "Core", "dcim": "DCIM", "extras": "Extras", "ipam": "IPAM",
	"tenancy": "Tenancy", "users": "Users", "virtualization": "Virtualization", "vpn": "VPN", "wireless": "Wireless",
}

const resourceDocTemplate = `---
page_title: "{{.Name}} {{.Type}} - {{.RenderedProviderName}}"
subcategory: "%s"
description: |-
{{ .Description | plainmarkdown | trimspace | prefixlines "  " }}
---

# {{.Name}} ({{.Type}})

{{ .Description | trimspace }}

{{ if .HasExample -}}
## Example Usage

{{ tffile .ExampleFile }}
{{- end }}

{{ .SchemaMarkdown | trimspace }}
{{- if .HasImport }}

## Import

Import is supported using the following syntax:

{{ codefile "shell" .ImportFile }}
{{- end }}
`

const dataSourceDocTemplate = `---
page_title: "{{.Name}} {{.Type}} - {{.RenderedProviderName}}"
subcategory: "%s"
description: |-
{{ .Description | plainmarkdown | trimspace | prefixlines "  " }}
---

# {{.Name}} ({{.Type}})

{{ .Description | trimspace }}

{{ if .HasExample -}}
## Example Usage

{{ tffile .ExampleFile }}
{{- end }}

{{ .SchemaMarkdown | trimspace }}
`

// writeDocTemplates writes per-type tfplugindocs templates so pages are grouped
// by NetBox app in the registry sidebar.
func writeDocTemplates(r *model.Resource, dir string) error {
	if dir == "" {
		return nil
	}
	title := appTitles[r.App]
	if title == "" {
		title = strings.ToUpper(r.App[:1]) + r.App[1:]
	}
	if !r.DataSourceOnly {
		if err := os.MkdirAll(filepath.Join(dir, "resources"), 0o750); err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join(dir, "resources", r.Name+".md.tmpl"), []byte(fmt.Sprintf(resourceDocTemplate, title)), 0o600); err != nil {
			return err
		}
	}
	if err := os.MkdirAll(filepath.Join(dir, "data-sources"), 0o750); err != nil {
		return err
	}
	for _, n := range []string{r.Name, r.Plural} {
		if err := os.WriteFile(filepath.Join(dir, "data-sources", n+".md.tmpl"), []byte(fmt.Sprintf(dataSourceDocTemplate, title)), 0o600); err != nil {
			return err
		}
	}
	return nil
}

// writeObjectTypes emits a map from NetBox content type label ("dcim.site") to
// API path for every collection, used by hand-written resources that address
// arbitrary objects (netbox_custom_field_value).
func writeObjectTypes(resources []*model.Resource, version, outDir string) error {
	dir := filepath.Join(outDir, "objecttypes")
	if err := os.MkdirAll(dir, 0o750); err != nil {
		return err
	}
	var b strings.Builder
	fmt.Fprintf(&b, generatedHeader, version)
	b.WriteString("// Package objecttypes maps NetBox content type labels to API paths.\npackage objecttypes\n\n")
	b.WriteString("// Paths maps a content type label (\"dcim.site\") to its collection path.\nvar Paths = map[string]string{\n")
	for _, r := range resources {
		if r.Skip {
			continue
		}
		fmt.Fprintf(&b, "\t%q: %q,\n", r.ObjectType(), r.Path)
	}
	b.WriteString("}\n\n// TerraformTypes maps a content type label to the Terraform resource type managing it (\"\" for read-only).\nvar TerraformTypes = map[string]string{\n")
	for _, r := range resources {
		if r.Skip {
			continue
		}
		tf := r.TFType()
		if r.DataSourceOnly {
			tf = ""
		}
		fmt.Fprintf(&b, "\t%q: %q,\n", r.ObjectType(), tf)
	}
	b.WriteString("}\n")
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return fmt.Errorf("format objecttypes.go: %w", err)
	}
	return os.WriteFile(filepath.Join(dir, "objecttypes.go"), src, 0o600)
}
