#!/usr/bin/env python3
"""Post-process openapi-generator output in ./netbox.

- Prefix every generated file with a ``// Code generated ... DO NOT EDIT.`` header
  (openapi-generator's header is not recognised by Go tooling).
- Relax the generated ``UnmarshalJSON`` required-property check that rejects
  legitimately empty strings (go-netbox PR #218).
"""
import glob
import os
import re
import sys

out, version = sys.argv[1], sys.argv[2]
header = f"// Code generated by openapi-generator from the NetBox {version} OpenAPI document. DO NOT EDIT.\n\n"
empty_check = re.compile(r'if value, exists := allProperties\[requiredProperty\]; !exists \|\| value == "" \{')
for path in glob.glob(os.path.join(out, "*.go")):
    if path.endswith("_extra.go") or path.endswith("_extra_test.go"):
        continue
    with open(path) as f:
        src = f.read()
    if not src.startswith("// Code generated"):
        src = header + src
    src = empty_check.sub("if _, exists := allProperties[requiredProperty]; !exists {", src)
    with open(path, "w") as f:
        f.write(src)
